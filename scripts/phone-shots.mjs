// Captures every page at phone size (and the typed meal flow) for layout review.
import { chromium } from 'playwright-core'
import path from 'node:path'
const out = process.argv[2] ?? 'shots'
const wait = (ms) => new Promise((r) => setTimeout(r, ms))
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' })
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
const p = await ctx.newPage()
p.on('pageerror', (e) => console.log('pageerror', e.message))
p.on('console', (m) => m.type() === 'error' && console.log('console', m.text()))
await p.goto('http://localhost:4173/?demo')
await p.fill('input[placeholder="e.g. Alex"]', 'mij')
await p.click('text=Create profile')
await p.click('text=Explore with sample data')
await p.waitForSelector("text=Today's nutrition")
await wait(1500)
const full = async (name) => { await wait(1200); await p.screenshot({ path: path.join(out, `m-${name}.png`), fullPage: true }); console.log('saved', name) }
const nav = async (label) => { await p.getByRole('button', { name: label, exact: true }).click() }
await full('dashboard')
await nav('Meals'); await wait(800)
await p.fill('textarea', '2 medium eggs scrambled, 1 table spoon of butter\n1 mug coffee with 2 tsp sugar, 1 cup kanin, tapsilog, kwek kwek')
await full('meals-typed')
await p.click('text=Review and log'); await wait(900)
await p.screenshot({ path: path.join(out, 'm-meals-review.png') })
await p.getByRole('button', { name: 'Close' }).click(); await wait(600)
await p.fill('textarea', '2 eggs, 1 cup rice, 1 banana')
await wait(500)
const before = await p.locator('.meal-row').count()
await p.locator('button', { hasText: /^Log (breakfast|lunch|snack|dinner)$/ }).click(); await wait(1200)
const after = await p.locator('.meal-row').count()
console.log('meal rows', before, '->', after, 'textarea now', JSON.stringify(await p.inputValue('textarea')))
await full('meals-logged')
await nav('Workouts'); await full('workouts')
await nav('Splits'); await full('splits')
await p.locator('.split-card, [data-split]').first().click().catch(async () => { await p.locator('text=Push / Pull / Legs').first().click() })
await full('split-detail')
await nav('Progress'); await full('progress')
await nav('Settings'); await full('settings')
await browser.close()
